#!/usr/bin/env bash
# host/pool-code.ts, as committed: the Pool contract's compiled template and its constructor slots, read from
# skein-amm's src/fixtures/pool_artifact.zig at the tag below (generated there from pool/Pool.runar.go), so the host's
# swap relay reads a pool's CommissionBps exactly as skein-amm's src/pool.zig `parse` does (host/relay.ts, the
# commission rule; skein-amm programs/amm-p2p/README.md "The commission rule").
#   AMM_DIR=<a skein-amm checkout at the tag> scripts/pool-code.sh     (default ../skein-amm)
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
AMM_TAG=v0.55.0
AMM_DIR="${AMM_DIR:-$(pwd)/../skein-amm}"
want="$(git -C "$AMM_DIR" rev-parse "${AMM_TAG}^{commit}" 2>/dev/null || true)"
have="$(git -C "$AMM_DIR" rev-parse HEAD)"
[ -z "${ALLOW_UNTAGGED:-}" ] && { [ "$want" = "$have" ] || { echo "pool-code.sh: $AMM_DIR is at $have, not skein-amm ${AMM_TAG} (${want:-no such tag}): check the tag out there (a worktree)" >&2; exit 1; }; }
src="$AMM_DIR/src/fixtures/pool_artifact.zig"
hex="$(sed -n 's/^pub const script_hex = "\([0-9a-f]*\)";$/\1/p' "$src")"
slots="$(sed -n 's/^    \.{ \.offset = \([0-9]*\), \.param = \([0-9]*\) },$/  { offset: \1, param: \2 },/p' "$src")"
param() { sed -n "s/^pub const param_$1 = \([0-9]*\);\$/\1/p" "$src"; }
[ -n "$hex" ] && [ -n "$slots" ] || { echo "pool-code.sh: $src: no script_hex or slots" >&2; exit 1; }
cat > host/pool-code.ts <<TS
// Generated by scripts/pool-code.sh from skein-amm ${AMM_TAG} src/fixtures/pool_artifact.zig (itself generated from
// pool/Pool.runar.go): do not edit. The compiled Pool template — its code with a one-byte OP_0 placeholder at each
// constructor slot (the readonly args, spliced in as pushes) — and the slots, as skein-amm's src/pool.zig reads them.
export const POOL_TEMPLATE_HEX = "${hex}";
export const POOL_SLOTS: ReadonlyArray<{ offset: number; param: number }> = [
${slots}
];
export const PARAM_ASSET_ID = $(param asset_id);
export const PARAM_LP_FEE_BPS = $(param lp_fee_bps);
export const PARAM_VALIDATOR_FEE_BPS = $(param validator_fee_bps);
export const PARAM_COMMISSION_BPS = $(param commission_bps);
TS
echo "host/pool-code.ts <- skein-amm ${AMM_TAG} src/fixtures/pool_artifact.zig"
